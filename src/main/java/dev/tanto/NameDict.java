package dev.tanto;

public class NameDict {
    String huName;
    String itaName;
    public NameDict() {
    }
    public NameDict(String huName, String itaName) {
        this.huName = huName;
        this.itaName = itaName;
    }
    public String getHuName() {
        return huName;
    }
    public void setHuName(String huName) {
        this.huName = huName;
    }
    public String getItaName() {
        return itaName;
    }
    public void setItaName(String itaName) {
        this.itaName = itaName;
    }

}
